#!/usr/bin/env python
"""TB1, the baseline throughput table, assembled from the committed M4 runs.

    python tb1.py             # markdown to stdout
    python tb1.py --latex     # also writes ../../paper/generated/tb1.tex

Sources: `results-m4-a100-run2` (GPU) and `results-m4-tpu-v5e8` (TPU), the runs
whose READMEs and docs/03 M4 describe the protocol. D=1 is the like-for-like
comparison (none of the references shards, so at D=8 they idle seven devices);
the D=8 shardes rows are reported separately as what sharding adds, never as a
ratio against an unsharded arm. Failed arms render as entries, not absences:
an OOM is a result (on the v5e it is the ravel_pytree foreclosure, measured).

Token-position evaluations per second, tokens = population * batch * seq: the unit both papers report
and the only one that survives comparing different population sizes.
"""

from __future__ import annotations

import argparse
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent

#: Per platform, in preference order: the first directory holding m4-d{D}.json
#: wins. The A100 D=1 rerun lives in run2; its D=8 rows are in results-m4.
SOURCES = [
    ("A100", [HERE / "results-m4-a100-run2", HERE / "results-m4"]),
    ("TPU v5e", [HERE / "results-m4-tpu-v5e8"]),
]
#: Presentation order: our arms, then the references.
ARMS = ["shardes/mirrored_lr1/B", "shardes/seed_regenerated/B", "eggroll/rank1",
        "naive_es", "evosax/Open_ES"]


def rows_for(paths: list[pathlib.Path], devices: int) -> dict:
    f = next((p / f"m4-d{devices}.json" for p in paths
              if (p / f"m4-d{devices}.json").exists()), None)
    if f is None:
        return {}
    out = {}
    for row in json.loads(f.read_text())["rows"]:
        key = (row["d_model"], row["population"], row["arm"])
        if "tokens_per_second" in row:
            out[key] = (row["tokens_per_second"], row["sharded"])
        else:
            out[key] = ("OOM", False)
    return out


def fmt(v) -> str:
    if v == "OOM":
        return "OOM"
    if v is None:
        return "--"
    return f"{v / 1e6:.2f}M" if v >= 1e6 else f"{v / 1e3:.0f}k"


def build(devices: int):
    """[(shape, {platform: {arm: value}})], shapes present in any source."""
    per = {name: rows_for(p, devices) for name, p in SOURCES}
    shapes = sorted({(k[0], k[1]) for r in per.values() for k in r})
    table = []
    for d, n in shapes:
        cell = {name: {a: (r.get((d, n, a)) or [None])[0] for a in ARMS}
                for name, r in per.items()}
        table.append(((d, n), cell))
    return table


def markdown() -> list[str]:
    lines = []
    for devices, title in ((1, "TB1: token-position evaluations/s at D=1 (like-for-like; no reference shards)"),
                           (8, "TB1b: D=8, what sharding adds (references idle 7 devices; not a ratio)")):
        lines += [f"**{title}**", "",
                  "| shape | platform | " + " | ".join(a.split("/")[-2 if a.startswith("shardes") else -1] if "/" in a else a for a in ARMS) + " |",
                  "|---|---|" + "---|" * len(ARMS)]
        for (d, n), cell in build(devices):
            for name, vals in cell.items():
                lines.append(f"| d={d}, N={n} | {name} | "
                             + " | ".join(fmt(vals[a]) for a in ARMS) + " |")
        lines.append("")
    return lines


def latex() -> str:
    def esc(s):
        return s.replace("_", "\\_")
    out = ["% generated by experiments/phase2/tb1.py; do not edit by hand"]
    for devices, caption, label in (
        (1, "Throughput at matched shapes, one device. Token-position evaluations per second, "
            "tokens = population $\\times$ batch $\\times$ sequence. "
            "OOM: the arm does not fit the device at this shape.", "tb1"),
        (8, "Eight devices: what sharding adds. The references have no "
            "sharding path and idle seven devices: on the v5e they were run "
            "at $D{=}8$ anyway and reproduce their $D{=}1$ rows, on the A100 "
            "they were not rerun (dashes). These rows are context, "
            "not a like-for-like ratio.", "tb1b"),
    ):
        # Short arm names as headers (the caption carries the full protocol);
        # the full identifiers at \small were 78pt wider than the page.
        short = [a.split("/")[1] if a.startswith("shardes/") else a.split("/")[0]
                 for a in ARMS]
        out += [f"\\begin{{table*}}", "\\centering", "\\small",
                "\\setlength{\\tabcolsep}{5pt}",
                f"\\caption{{{caption}}}", f"\\label{{tab:{label}}}",
                "\\begin{tabular}{ll" + "r" * len(ARMS) + "}", "\\toprule",
                "shape & platform & " + " & ".join(esc(a) for a in short) + " \\\\",
                "\\midrule"]
        for (d, n), cell in build(devices):
            for name, vals in cell.items():
                out.append(f"$d{{=}}{d}$, $N{{=}}{n}$ & {name} & "
                           + " & ".join(fmt(vals[a]) for a in ARMS) + " \\\\")
        out += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    args = ap.parse_args()
    print("\n".join(markdown()))
    if args.latex:
        dest = HERE.parent.parent / "paper" / "generated" / "tb1.tex"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(latex())
        print(f"wrote {dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
