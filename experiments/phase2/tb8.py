#!/usr/bin/env python
"""TB8: what the two placements' collectives cost in time, on both fabrics.

    python tb8.py             # markdown to stdout
    python tb8.py --latex     # also writes ../../paper/generated/tb8.tex

Source: `results-ladder/*.json` (allreduce_ladder.py). TB2 reports the payload each
placement moves and Section 6 reports end-to-end seconds; this is the term between them,
so the sentence "B wins whenever the contraction it avoids costs more than those bytes"
stops being an assertion about bytes and becomes an arithmetic about time.

The `step` column is the number to read, not `call`. `call` times a program whose only
content is the collective, so it carries the whole dispatch and synchronization floor
(0.32 ms on the A100, 0.60 ms on the v5e), which no generation pays twice. `step` is the
slope of a dependent chain, the marginal cost of one more collective inside a program that
is already running, which is where the psum actually sits.

Two rows per fabric are the ones the placements issue: $4P$ at $d{=}512$ and $d{=}2048$
(six square float32 matrices, 6 and 96 MiB) for B's all-reduce, and $4N$ for the fitness
gather both placements share. The rest of the ladder is there so the reader can see the
latency floor and the bandwidth slope that produce them.
"""

from __future__ import annotations

import argparse
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent

PLATFORMS = (
    ("8$\\times$A100 (NVLink)", "8x A100 (NVLink)",
     "results-ladder/ladder-nvidia-a100-sxm4-80gb-D8.json"),
    ("TPU v5e-8 (ICI)", "TPU v5e-8 (ICI)",
     "results-ladder/ladder-tpu-v5-lite-D8.json"),
)

#: payload bytes -> what issues it. 6 d^2 float32 for the block's six square matrices.
ANNOTATE = {
    8: "latency floor",
    1024: "",
    2**20: "",
    6 * 512**2 * 4: "B's all-reduce, $d{=}512$",
    6 * 2048**2 * 4: "B's all-reduce, $d{=}2048$",
    100 * 2**20: "bandwidth point",
}


def load():
    out = []
    for latex_name, md_name, rel in PLATFORMS:
        path = HERE / rel
        if not path.exists():
            continue
        rec = json.loads(path.read_text())
        rows = []
        for k, v in sorted(rec["allreduce"].items(), key=lambda kv: int(kv[0])):
            rows.append(("all-reduce", int(k), ANNOTATE.get(int(k), ""),
                         v["call"]["median"], v["step_seconds"]))
        for k, v in sorted(rec["allgather"].items(), key=lambda kv: int(kv[0])):
            n = int(k)
            rows.append(("all-gather", 4 * n, f"fitness gather, $N{{=}}{n}$",
                         v["call"]["median"], v["step_seconds"]))
        out.append((latex_name, md_name, rec, rows))
    return out


def size(nbytes: int) -> str:
    for unit, div in (("MiB", 2**20), ("KiB", 2**10)):
        if nbytes >= div:
            v = nbytes / div
            return f"{v:.0f}\\,{unit}" if v == int(v) else f"{v:.1f}\\,{unit}"
    return f"{nbytes}\\,B"


def markdown() -> list[str]:
    out = ["**TB8: isolated collective cost on both fabrics, D=8**", ""]
    for _, name, rec, rows in load():
        beta = rec["beta_bytes_per_second"] / 2**30
        out += [f"*{name}*  (alpha {rec['alpha_seconds'] * 1e6:.0f} us, "
                f"beta {beta:.0f} GiB/s, one-op floor "
                f"{rec['call_floor_seconds'] * 1e3:.2f} ms)", "",
                "| collective | payload | issued by | call (us) | step (us) |",
                "|---|---|---|---|---|"]
        for kind, nbytes, note, call, step in rows:
            out.append("| %s | %s | %s | %.0f | %.1f |"
                       % (kind, size(nbytes).replace("\\,", " "),
                          note.replace("$", "").replace("{=}", "="),
                          call * 1e6, step * 1e6))
        out.append("")
    return out


def latex() -> str:
    out = ["% generated by experiments/phase2/tb8.py; do not edit by hand",
           "\\begin{table*}", "\\centering", "\\small",
           "\\caption{What the two placements' collectives cost in time, timed in "
           "isolation on the full local mesh at $D{=}8$. \\emph{call} is a program whose "
           "only content is the collective, so it carries the dispatch and "
           "synchronization floor; \\emph{step} is the slope of a dependent chain, the "
           "marginal cost of one more collective inside a program that is already "
           "running, which is where the contraction's psum sits. The two rows a "
           "placement actually issues are B's all-reduce at $4P$ and the $4N$ fitness "
           "gather. Bytes reach time through a payload-dependent rate: the v5e starts "
           "sooner and finishes the 96\\,MiB transfer in twice the A100's time, which is "
           "the whole reason the same byte counts give a different crossover on the two "
           "platforms.}",
           "\\label{tab:tb8}",
           "\\begin{tabular}{llrrr}", "\\toprule",
           "collective & payload & issued by & call ($\\mu$s) & step ($\\mu$s) \\\\"]
    for name, _, rec, rows in load():
        beta = rec["beta_bytes_per_second"] / 2**30
        out += ["\\midrule",
                "\\multicolumn{5}{l}{\\emph{%s}: $\\alpha$ %.0f\\,$\\mu$s, $\\beta$ "
                "%.0f\\,GiB/s, one-op floor %.2f\\,ms} \\\\"
                % (name, rec["alpha_seconds"] * 1e6, beta,
                   rec["call_floor_seconds"] * 1e3),
                "\\midrule"]
        for kind, nbytes, note, call, step in rows:
            out.append("%s & %s & %s & %.0f & %.1f \\\\"
                       % (kind, size(nbytes), note, call * 1e6, step * 1e6))
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    args = ap.parse_args()
    print("\n".join(markdown()))
    if args.latex:
        dest = HERE.parent.parent / "paper" / "generated" / "tb8.tex"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(latex())
        print(f"wrote {dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
