#!/usr/bin/env python
"""TB2: communication, analytic prediction against measured bytes.

    python tb2.py             # markdown to stdout
    python tb2.py --latex     # also writes ../../paper/generated/tb2.tex

Source: `comms-consistent.json` (comms.py counts the payload of every collective
the compiled update performs; the analytic column is the cost model written
before the measurement, docs/03 M5). The table reports D=8 rows per
(strategy, contraction): predicted bytes, measured bytes, and the ratio.

The two systematic deviations ARE the table's content, not noise to hide:

- Strategy A measures 2x its naive prediction: the sharding fix made two f32[N]
  gathers real (fitness in, weights out), so the folk claim "ES only
  communicates scalars" holds in order of magnitude with a constant of 2.
- Strategy B measures its model-sized all-reduce plus 4N: the same fitness
  gather rides along. The all-reduce dominates by three orders of magnitude.
- At D=1 the compiler emits no collectives at all, so measured is 0 where the
  abstract model still counts a payload; those rows are excluded rather than
  averaged in as agreement.
"""

from __future__ import annotations

import argparse
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE / "comms-consistent.json"


def rows():
    data = json.loads(SOURCE.read_text())
    keep = [r for r in data if r["devices"] == 8]
    out = {}
    for r in keep:
        key = (r["strategy"], r["how"], r["d_model"], r["population"])
        out[key] = (r["predicted"], r["bytes"])
    return out


def table():
    """Aggregate over shapes: one line per (strategy, how) with the ratio range."""
    per = {}
    for (s, how, d, n), (pred, got) in sorted(rows().items()):
        per.setdefault((s, how), []).append((d, n, pred, got))
    lines = []
    for (s, how), cells in sorted(per.items()):
        ratios = [g / p for _, _, p, g in cells if p]
        lo, hi = min(ratios), max(ratios)
        # representative largest shape for the absolute column
        d, n, pred, got = max(cells)
        lines.append((s, how, d, n, pred, got, lo, hi))
    return lines


def markdown() -> list[str]:
    out = ["**TB2: bytes per update at D=8, analytic vs measured (largest shape shown; ratio over all shapes)**", "",
           "| strategy | contraction | shape | predicted | measured | measured/predicted |",
           "|---|---|---|---|---|---|"]
    for s, how, d, n, pred, got, lo, hi in table():
        ratio = f"{lo:.2f}" if abs(hi - lo) < 0.005 else f"{lo:.2f}-{hi:.2f}"
        out.append(f"| {s} | {how} | d={d}, N={n} | {pred:,} | {got:,} | {ratio} |")
    out += ["", "D=1 rows excluded: the compiler emits no collectives on one device, "
            "so measured is 0 by construction there."]
    return out


def latex() -> str:
    def esc(x):
        return str(x).replace("_", "\\_")
    out = ["% generated by experiments/phase2/tb2.py; do not edit by hand",
           "\\begin{table*}", "\\centering", "\\small",
           "\\caption{Bytes moved per update at $D{=}8$: the cost model's "
           "prediction (written before the measurement) against the payload of "
           "every collective in the compiled update. Strategy A's factor of two "
           "is the pair of $4N$-byte gathers the sharded evaluation makes real; "
           "strategy B's excess is that same gather riding beside its "
           "model-sized all-reduce.}",
           "\\label{tab:tb2}",
           "\\begin{tabular}{llrrrr}", "\\toprule",
           "strategy & contraction & shape & predicted & measured & ratio \\\\",
           "\\midrule"]
    for s, how, d, n, pred, got, lo, hi in table():
        ratio = f"{lo:.2f}" if abs(hi - lo) < 0.005 else f"{lo:.2f}--{hi:.2f}"
        out.append(f"{esc(s)} & {how} & $d{{=}}{d}$, $N{{=}}{n}$ & "
                   f"{pred:,} & {got:,} & {ratio} \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    args = ap.parse_args()
    print("\n".join(markdown()))
    if args.latex:
        dest = HERE.parent.parent / "paper" / "generated" / "tb2.tex"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(latex())
        print(f"wrote {dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
