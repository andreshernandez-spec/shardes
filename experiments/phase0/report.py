#!/usr/bin/env python
"""Regenerate experiments/phase0/README.md from results/ and env.json.

    python report.py            # rewrite README.md
    python report.py --check    # non-zero exit if README.md is stale

Every number in the E1 writeup comes from here, so there is nothing to retype when the
sweep is re-run and nothing to forget to update. CLAUDE.md ground rule 2: no claim enters a
markdown file without a script behind it and a recorded environment.

The prose that is *not* a number lives in PROSE below rather than in the generated file, so
regenerating never silently drops an interpretation someone wrote by hand.
"""

from __future__ import annotations

import argparse
import collections
import json
import pathlib
import statistics
import sys

HERE = pathlib.Path(__file__).resolve().parent
RESULTS = HERE / "results"
README = HERE / "README.md"

# Kept out of the generated tables on purpose: these are claims, not measurements, and a
# regeneration must not be able to quietly drop one.
PROSE = """
## Reading this

`d_eff` is the dimension **sample design operates in**, and it is a different quantity in
the two panels (`src/shardes/dimensions.py`). Under full rank it is the space `∇f` lives in;
under rank 1 it is `6·(512+512)`, while the products still live in `ℝ^1572864`. Compare the
panels at equal `N`, not at equal `N/d_eff`.

The bias column is **not** a correctness gate at `R = 30`. `‖E[ĝ] − ∇f‖/‖∇f‖` estimated from
30 replicates is dominated by the variance floor, not by any real bias; the unbiasedness gate
lives in `tests/test_estimator.py`, on the quadratic, at `R = 10000`. A large number here
means the estimator is noisy, which it is, and says nothing about whether it is biased.

`shaping = centered_ranks` is not estimating `∇f` at all. Its bias is large by design and
reading it as a failure would be a mistake (`docs/01` C0.5).

**`sigma = 0.1` is a dead arm on this block, and the sweep measured it rather than assuming
it.** At rank 1, `N = 2^18`: `cos = 0.370` at `sigma = 1e-3`, `0.162` at `1e-2`, and `0.0018`
at `1e-1`. The estimator targets the *smoothed* gradient `E[f(theta + sigma eps)]`, and by
`sigma = 0.1` the smoothing has moved the target far enough from `grad f` that the cosine is
two orders of magnitude down. That is a property of the objective, not a bug, and it is the
same shape of finding as `shaping = none` being dead here (`docs/01` C0.5).

It matters for reading F5: the figure defaults to `--sigma 0.01`, which is the middle arm.
The `1e-3` slice is uniformly better and is the one to check if a scheme comparison looks
flat, because a scheme can only separate where the estimator has signal to begin with.
"""


def load() -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted(RESULTS.glob("*.json"))]


def fmt_env(env: dict) -> str:
    rows = [
        ("commit", f"`{env['commit'][:12]}`"),
        ("dirty worktree", str(env["dirty_worktree"])),
        ("device", env["device_kind"]),
        ("device count", str(env["device_count"])),
        ("jax / jaxlib", f"{env['jax']} / {env['jaxlib']}"),
        ("numpy / scipy", f"{env['numpy']} / {env['scipy']}"),
        ("python", env["python"]),
        ("platform", env["platform"]),
        ("XLA_FLAGS", f"`{env['xla_flags'] or '(none)'}`"),
    ]
    return "\n".join(f"| {k} | {v} |" for k, v in rows)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if README.md differs from what this would write")
    args = ap.parse_args(argv)

    recs = load()
    if not recs:
        print(f"no results in {RESULTS}", file=sys.stderr)
        return 1

    envs = {json.dumps(r["env"], sort_keys=True) for r in recs}
    env = json.loads(next(iter(envs)))
    synthetic = sum(bool(r["SYNTHETIC"]) for r in recs)
    truncated = sum(bool(r["truncated"]) for r in recs)
    wall = sum(r["wall_clock_s"] for r in recs)
    reps = collections.Counter(r["replicates_completed"] for r in recs)

    # Per (rank, scheme), the cosine at the largest N available. This is the table F5 is a
    # picture of, so a reader can check the figure against numbers.
    best: dict = {}
    for r in recs:
        c = r["config"]
        if c["shaping"] not in ("centered", "none"):
            continue  # the unbiased baseline arm; see plot.py BASELINE
        k = (c["rank"], c["scheme"], c["sigma"])
        if k not in best or c["population"] > best[k]["config"]["population"]:
            best[k] = r

    lines = [
        "# E1 — estimator quality sweep",
        "",
        "**Generated by `report.py`. Do not edit by hand; edit the script or `PROSE` in it.**",
        "",
        f"{len(recs)} of 456 configs, "
        f"{'COMPLETE' if len(recs) == 456 else 'PARTIAL'}. "
        f"{wall / 3600:.2f} h of measured cell time.",
        "",
        "## Environment",
        "",
        "| | |",
        "|---|---|",
        fmt_env(env),
        "",
        f"Distinct environments across cells: **{len(envs)}** "
        f"({'uniform' if len(envs) == 1 else 'MIXED — see the warning below'}).",
        "",
    ]
    if len(envs) > 1:
        lines += ["> **Warning:** cells were produced under more than one environment. "
                  "Per-cell `env` records which.", ""]
    if synthetic:
        lines += [f"> **Warning:** {synthetic} cell(s) are SYNTHETIC dry-run output.", ""]

    lines += [
        "## Integrity",
        "",
        "| check | value |",
        "|---|---|",
        f"| replicates per cell | {dict(reps)} |",
        f"| truncated by the wall-clock cap | {truncated} |",
        f"| synthetic cells | {synthetic} |",
        "",
        "## Cosine at the largest N, unbiased baseline arm",
        "",
        "| rank | scheme | sigma | N | N/d_eff | cos (median) | IQR | rel. bias |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for (rank, scheme, sigma), r in sorted(best.items(), key=lambda kv: (str(kv[0][0]), kv[0][1], kv[0][2])):
        c = r["config"]
        lines.append(
            f"| {rank} | `{scheme}` | {sigma:g} | {c['population']} | "
            f"{c['population'] / r['d_eff']:.3g} | {r['cosine_median']:.4f} | "
            f"{r['cosine_q1']:.4f}–{r['cosine_q3']:.4f} | {r['relative_bias']:.3g} |"
        )

    # Per-replicate cost is quoted at the strategy's largest N. A median across the whole
    # population axis mixes 2^6 with 2^18 and means nothing.
    lines += [
        "",
        "## Cost",
        "",
        "| strategy | cells | largest N | s/replicate there | total min |",
        "|---|---|---|---|---|",
    ]
    by = collections.defaultdict(list)
    for r in recs:
        by[r["config"]["strategy"]].append(r)
    for name in sorted(by):
        rs = by[name]
        top = max(x["config"]["population"] for x in rs)
        per = statistics.median(
            x["wall_clock_s"] / max(x["replicates_completed"], 1)
            for x in rs if x["config"]["population"] == top
        )
        lines.append(f"| `{name}` | {len(rs)} | {top} | {per:.3f} | "
                     f"{sum(x['wall_clock_s'] for x in rs) / 60:.1f} |")

    lines += ["", PROSE.strip(), "",
              "## Reproduce", "",
              "```sh", "cd experiments/phase0", "python run.py       # resumable",
              "python plot.py      # figures/f5-estimator-quality.png",
              "python report.py    # this file", "```", ""]

    text = "\n".join(lines)
    if args.check:
        current = README.read_text() if README.exists() else ""
        if current != text:
            print("README.md is stale; run report.py", file=sys.stderr)
            return 1
        return 0

    README.write_text(text)
    print(f"wrote {README} ({len(recs)} cells)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
