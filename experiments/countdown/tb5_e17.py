#!/usr/bin/env python
"""Table 5 from results-e17: the contraction crossover on the real model.

    python tb5_e17.py            # markdown to stdout
    python tb5_e17.py --latex    # also writes paper/generated/tb5.tex

Reads only the committed results-e17 JSONs. Cells where a side ran out of
memory print as OOM; the one absent cell (rank 1, B, N=240, D=8, killed in
compilation with its A sibling over HBM) prints as a dash.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results-e17"

ARMS = [("mirrored_seed", "full rank (seed)"), ("mirrored_lr1", "rank 1")]


def cell(strategy: str, how: str, n: int, d: int):
    f = RESULTS / f"s={strategy}__how={how}__N={n}__D={d}.json"
    if not f.exists():
        return None
    rec = json.loads(f.read_text())
    return rec.get("seconds_median", "oom")


def ratio(strategy: str, n: int, d: int) -> str:
    a, b = cell(strategy, "A", n, d), cell(strategy, "B", n, d)
    if a is None or b is None:
        return "--"
    if a == "oom" or b == "oom":
        return "OOM"
    return f"${math.log10(b / a):+.3f}$"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    args = ap.parse_args(argv)

    rows = []
    for strategy, label in ARMS:
        for n in (32, 240):
            rows.append((label, n, [ratio(strategy, n, d) for d in (1, 2, 4, 8)]))

    print("| arm | N | D=1 | D=2 | D=4 | D=8 |")
    print("|---|---|---|---|---|---|")
    for label, n, vals in rows:
        print(f"| {label} | {n} | " + " | ".join(vals) + " |")

    if args.latex:
        out = HERE.parent.parent / "paper" / "generated" / "tb5.tex"
        body = [f"{label} & {n} & " + " & ".join(vals) + r" \\"
                for label, n, vals in rows]
        out.write_text("\n".join([
            "% generated by experiments/countdown/tb5_e17.py --latex; do not edit",
            r"\begin{table*}[t]", r"\centering", r"\small",
            r"\caption{The contraction crossover on the real model "
            r"(Qwen2.5-0.5B, one production update on the fixed prompt "
            r"batch, TPU v5e): $\log_{10}(t_B/t_A)$ of median generation "
            r"time, negative where the model-sized all-reduce placement "
            r"wins. OOM: the shape does not fit the per-cell device count "
            r"on 16\,GB chips (recorded outcomes); the dash is one cell "
            r"killed in compilation whose A sibling exceeded memory at the "
            r"same shape.}",
            r"\label{tab:tb5}",
            r"\begin{tabular}{llrrrr}", r"\toprule",
            r"arm & $N$ & $D{=}1$ & $D{=}2$ & $D{=}4$ & $D{=}8$ \\",
            r"\midrule",
            *body,
            r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]))
        print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
