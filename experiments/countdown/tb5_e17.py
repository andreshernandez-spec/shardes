#!/usr/bin/env python
"""Table 5 from results-e17b: what one real-model update actually costs.

    python tb5_e17.py            # markdown to stdout
    python tb5_e17.py --latex    # also writes paper/generated/tb5.tex

This used to print $\\log_{10}(t_B/t_A)$ over the four cells of `results-e17`,
which F9 now covers from `results-e17b` over 32 cells of the same driver, on
the same platform, at four populations and four arms. Two tables of the same
ratio, one a strict subset of the other, and the caption justified keeping it
by wall-clock figures it did not contain.

So it prints the wall clock instead, which nothing else in the paper does. F9
gives the ratio between the placements; this gives the level. Together they
determine both placements' times, and separately they answer the two questions
a reader actually has: which placement, and how long.

The cell is the faster of the two placements, since that is what a user who
picks correctly pays. A cell is OOM only if both placements exceeded HBM;
where one placement fits and the other does not, the one that fits is the
entry and F9 carries the asymmetry.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results-e17b"

ARMS = [("mirrored_seed", "full rank (seed)"), ("mirrored_lr1", "rank 1"),
        ("mirrored_lr4", "rank 4"), ("mirrored_lr16", "rank 16")]
POPULATIONS = (32, 64, 128, 240)
DEVICES = (1, 2, 4, 8)


def cell(strategy: str, how: str, n: int, d: int):
    f = RESULTS / f"s={strategy}__how={how}__N={n}__D={d}.json"
    if not f.exists():
        return None
    rec = json.loads(f.read_text())
    return "oom" if rec.get("status") == "oom" else rec.get("seconds_median")


def best(strategy: str, n: int, d: int) -> str:
    """The faster placement in ms, or OOM when neither fits."""
    times = [t for t in (cell(strategy, "A", n, d), cell(strategy, "B", n, d))
             if isinstance(t, float)]
    if times:
        return f"{min(times) * 1e3:.0f}"
    both = (cell(strategy, "A", n, d), cell(strategy, "B", n, d))
    return "OOM" if "oom" in both else "--"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    args = ap.parse_args(argv)

    rows = []
    for strategy, label in ARMS:
        for n in POPULATIONS:
            rows.append((label, n, [best(strategy, n, d) for d in DEVICES]))

    print("| arm | N | D=1 | D=2 | D=4 | D=8 |")
    print("|---|---|---|---|---|---|")
    for label, n, vals in rows:
        print(f"| {label} | {n} | " + " | ".join(vals) + " |")

    if args.latex:
        out = HERE.parent.parent / "paper" / "generated" / "tb5.tex"
        body = [f"{label} & {n} & " + " & ".join(vals) + r" \\"
                for label, n, vals in rows]
        out.write_text("\n".join([
            "% generated by experiments/countdown/tb5_e17.py --latex; do not edit",
            r"\begin{table*}[t]", r"\centering", r"\small",
            r"\caption{What one real-model update costs, in milliseconds "
            r"(Qwen2.5-0.5B, one full ask--teacher-forced-NLL--tell update on "
            r"the fixed prompt batch, TPU v5e-8, median of five timed repeats). "
            r"Each entry is the faster of the two contraction placements, which "
            r"is what a user who picks correctly pays; "
            r"Figure~\ref{fig:f9} gives the ratio between them over the same "
            r"grid, so the two together determine both placements at every "
            r"cell. OOM: neither placement fits 16\,GB chips at that shape "
            r"(recorded outcomes, not skipped cells). The seed arm is the only "
            r"one that reaches $N{=}240$, and it pays 4.6\,s an update there "
            r"against rank 1's 230\,ms at $N{=}128$.}",
            r"\label{tab:tb5}",
            r"\begin{tabular}{llrrrr}", r"\toprule",
            r"arm & $N$ & $D{=}1$ & $D{=}2$ & $D{=}4$ & $D{=}8$ \\",
            r"\midrule",
            *body,
            r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]))
        print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
