#!/usr/bin/env python
"""Generate E14's perturbed configs from the committed E13 bases.

    python e14_make_configs.py     # writes e14/*.yaml, prints what and why

A script rather than hand-edited copies so the derivation is reviewable: each
config is the E13 base with exactly one dial multiplied, the horizon cut to 150,
and its own results_dir. The multiplier-1 columns are NOT generated: they are
E13's committed runs read at the same horizon (docs/08).

Note on the ES sigma arm: the library's step is lr/(N*sigma), so scaling sigma
at fixed lr also scales the relative step. That coupling is the published
parameterization (sigma-relative steps are the load-bearing part, per the
pilot config's own note), so the sigma arm perturbs the noise scale as a user
of the published recipe would experience it.
"""

from __future__ import annotations

import pathlib

import yaml

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "e14"

CELLS = [
    # (base config, dial, multiplier or absolute, slug)
    # x1 drift baseline (added 2026-08-21): the E14 table compares perturbed
    # drift against GRPO but E13's x1 runs predate the metric; three published-
    # settings runs at the E14 horizon fill the column.
    ("pilot-lr1.yaml", "lr", 1, "es-x1"),
    ("pilot-lr1.yaml", "lr", 1 / 8, "es-lr-eighth"),
    ("pilot-lr1.yaml", "lr", 8, "es-lr-8x"),
    ("pilot-lr1.yaml", "sigma", 1 / 4, "es-sigma-quarter"),
    ("pilot-lr1.yaml", "sigma", 4, "es-sigma-4x"),
    ("grpo.yaml", "lr", 1 / 8, "grpo-lr-eighth"),
    ("grpo.yaml", "lr", 8, "grpo-lr-8x"),
    ("grpo.yaml", "kl_beta", 0.0, "grpo-beta-0"),
    # Second single-stabilizer ablation (added 2026-08-20 after the research
    # spike): the ratio clip widened to where it never binds. The entropy
    # literature ties collapse dynamics to the clip; Engstrom et al. found
    # PPO-NoClip can match PPO, so this arm is informative whichever way it
    # lands, and that is why it is worth its three runs.
    ("grpo.yaml", "clip_epsilon", 10.0, "grpo-clip-off"),
]
ABSOLUTE = {"kl_beta", "clip_epsilon"}  # set, not multiplied
HORIZON = 150  # three eval points past E13's failure onset (~step 50)


def main() -> int:
    OUT.mkdir(exist_ok=True)
    for base, dial, value, slug in CELLS:
        cfg = yaml.safe_load((HERE / base).read_text())
        if base == "grpo.yaml":
            # TRL's default, made explicit so every generated config carries the
            # clip it ran with; the clip-off cell overwrites it below.
            cfg.setdefault("clip_epsilon", 0.2)
        if dial in ABSOLUTE:
            cfg[dial] = float(value)
            note = f"{dial}: {value} (stabilizer ablation; published "
            note += "1e-3)" if dial == "kl_beta" else "0.2)"
        else:
            cfg[dial] = float(cfg[dial]) * value
            note = f"{dial}: x{value} of published"
        for key in ("generations", "steps"):
            if key in cfg:
                cfg[key] = HORIZON
        cfg["results_dir"] = f"results-e14-{slug}"
        text = (f"# E14 cell {slug}: {base} with {note}, horizon {HORIZON}.\n"
                f"# Generated by e14_make_configs.py; edit the generator, not this.\n"
                + yaml.safe_dump(cfg, sort_keys=False))
        (OUT / f"{slug}.yaml").write_text(text)
        print(f"{slug}: {note}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
