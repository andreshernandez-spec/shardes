#!/usr/bin/env python
"""E16 as a table: the cross-batch gate and the cross-scale calibration.

    python tb6_e16.py            # print the grid
    python tb6_e16.py --latex    # also write paper/generated/tb6.tex

Reads only committed artifacts: E1's update--gradient-alignment results (the fit),
E16's per-cell JSONs, and the model configs. The raw predictions are the
committed E1 fit (sigma 1e-3, centered ranks) evaluated at each cell's
N/d_samp, exactly the values frozen (rounded) in e16-gate.yaml and
e16-stage2.yaml before the runs; the calibrated prediction is raw times
the 0.53 geometric-mean correction E15 measured at 0.5B, the constant
frozen in e16-stage2.yaml. No number here is fit to E16's measurements.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import jax
import jax.numpy as jnp

from analysis_e15 import e1_curve, fit_predict

HERE = Path(__file__).resolve().parent
import sys
sys.path.insert(0, str(HERE.parent.parent / "src"))
from shardes.dimensions import FULL, sampling_dimension  # noqa: E402
from shardes.problems import qwen2  # noqa: E402

CORRECTION = 0.53  # frozen in e16-stage2.yaml before the run

ROWS = [  # (results dir, model label, model config, calibrate rank-1?)
    ("results-e16-gate", "0.5B, new prompt batch", "qwen25_05b", False),
    ("results-e16-stage2", "1.5B", "qwen25_15b", True),
]
ARMS = {"mirrored_seed": ("full rank", "mirrored_full", FULL),
        "mirrored_lr1": ("rank 1", "mirrored_lr1", 1)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    args = ap.parse_args(argv)

    lines = []
    for rdir, label, config, calibrate in ROWS:
        cfg = getattr(qwen2.Config, config)()
        tree = jax.eval_shape(lambda: qwen2.init(jax.random.key(0), cfg,
                                                 dtype=jnp.bfloat16))
        for strategy, (name, e1_name, rank) in ARMS.items():
            d_eff = sampling_dimension(tree, rank)
            pts = e1_curve(e1_name, "centered_ranks")
            for f in sorted((HERE / rdir).glob(f"s={strategy}__N=*.json")):
                d = json.loads(f.read_text())
                n = d["config"]["population"]
                med = d["cosine_median"]
                cos = sorted(d["cosines"])
                raw = fit_predict(pts, n / d_eff)
                cal = raw * CORRECTION if (calibrate and rank == 1) else None
                lines.append((label, name, n, med, cos, raw, cal))

    w = max(len(l[0]) for l in lines)
    for label, name, n, med, cos, raw, cal in lines:
        s = (f"{label:{w}s}  {name:9s} N={n:<4d} measured {med:8.2e} "
             f"[{cos[0]:.1e}-{cos[-1]:.1e}]  raw {raw:8.2e} "
             f"ratio {med / raw:4.2f}x")
        if cal is not None:
            s += f"  calibrated {cal:8.2e} ratio {med / cal:4.2f}x"
        print(s)

    if args.latex:
        rows = []
        for label, name, n, med, cos, raw, cal in lines:
            meas = (f"${med * 1e4:.2f}$ [{cos[0] * 1e4:.1f}, {cos[-1] * 1e4:.1f}]")
            calc = (f"${cal * 1e4:.2f}$" if cal is not None else "--")
            calr = (f"${med / cal:.2f}\\times$" if cal is not None else "--")
            rows.append(f"{label} & {name} & {n} & {meas} & ${raw * 1e4:.2f}$ & "
                        f"${med / raw:.2f}\\times$ & {calc} & {calr} \\\\")
        out = HERE.parent.parent / "paper" / "generated" / "tb6.tex"
        out.write_text("\n".join([
            "% generated by experiments/countdown/tb6_e16.py --latex; do not edit",
            "\\begin{table*}[t]", "\\centering", "\\small",
            "\\caption{The bridge held out of sample. Centered-rank-update cosine",
            "  against the true teacher-forced-NLL gradient ($\\times 10^{-4}$;",
            "  median [min, max] over 5 seeds)",
            "  on a freshly drawn prompt batch at 0.5B and on Qwen2.5-1.5B,",
            "  against predictions committed before each run: the raw E1 fit at",
            "  each cell's $N/d_{\\mathrm{samp}}$, and for rank 1 at 1.5B the fit",
            "  times the 0.53 correction measured at 0.5B. Nothing in the",
            "  predicted columns is fit to these measurements.}",
            "\\label{tab:tb6}",
            "\\begin{tabular}{llllllll}", "\\toprule",
            "model & arm & $N$ & measured & raw & ratio & calibrated & ratio \\\\",
            "\\midrule",
            *rows,
            "\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]))
        print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
